import cv2

# функция с помощью которой можно за секунду отрисовать линию на кадре видео и посмотреть на результат в мини окне
# основные аргументы: 
# 1. adres - адрес на видео, на котором будем смотреть как рисуется линия
# 2. rgb - цвет в rgb, которого будет линия
# 3. thickness - толщина линии
# 4. point1 - первая точка линии
# 5. point2 - вторая точка линии
def show_line(adres, rgb, thickness, point1 = (0, 0), point2 = (960, 720)):

    # преобразуем видео
    video = cv2.VideoCapture(adres)

    # проверка на корректность открытия видео
    if not(video.isOpened()):
        raise RuntimeError('Видео не открылось!')

    # считываем успешность открытия кадра и сам кадр
    ret, frame = video.read()

    # если кадр достали успешно, то преобразовываем в нужный размер и рисуем линию по заданным в начале параметрам
    if ret:
        frame_with_new_size = cv2.resize(frame, (960, 720))
        cv2.line(frame_with_new_size, point1, point2, rgb, thickness=thickness)

    # показываем изображение с линией в всплывающем окне
    cv2.imshow('Изображение с выбранной вами линией', frame_with_new_size)
    # окно будет висеть до тех пор, пока пользователь не нажмет любую кнопку
    cv2.waitKey(0)
    # закрываем окно
    cv2.destroyAllWindows()
